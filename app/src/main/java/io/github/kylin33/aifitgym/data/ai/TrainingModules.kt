    /** 常驻的一句话，索引里显示；一句话说不清就别放进核心。 */
    val core: String,
    /** 命中这些词就认为这轮在聊这个专项。 */
    val keywords: List<String>,
    /** 命中后注入的详细规则。 */
    val body: String,
) {

