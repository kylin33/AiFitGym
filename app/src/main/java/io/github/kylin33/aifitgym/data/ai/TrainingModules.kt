/**
 * 决定这一轮加载哪些模块。
 *
 * 只用关键词命中数排序，不做语义判断 —— 判断错了的代价只是多注入几百字规则或
 * 少注入一段专项，都不致命；而让模型自己选模块，它会在每一轮都选「全都要」。
 */
object TrainingModuleSelector {

    /** 最多同时加载两个：再多就互相打架，也吃 token。 */
    const val MAX_ACTIVE = 2

    fun pick(text: String, limit: Int = MAX_ACTIVE): List<TrainingModule> {
        if (text.isBlank()) return emptyList()
        val lower = text.lowercase()
        return TrainingModule.entries
            .map { module -> module to module.keywords.count { lower.contains(it.lowercase()) } }
            .filter { it.second > 0 }
            // 命中数相同时按枚举顺序，保证同一句话每次选出来一样
            .sortedByDescending { it.second }
            .take(limit.coerceAtLeast(0))
            .map { it.first }
    }
}
