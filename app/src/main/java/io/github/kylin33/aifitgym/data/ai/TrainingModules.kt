package io.github.kylin33.aifitgym.data.ai

/**
 * 训练类型模块 —— 核心提示词之外的可插拔专项规则。
 *
 * ## 为什么要有这一层
 *
 * 角色、决策骨架、输出协议这三层是所有训练共用的，不该为「加一个跑步」而改动。
 * 专项知识（配速怎么加、HIIT 一周几次、增肌每组几次）放在这里，按话题**按需注入**：
 * 用户聊到跑步才把跑步那几段塞进 prompt，不聊就不花 token。
 *
 * 新增一个训练类型 = 在枚举里加一条，核心提示词一个字不用改。判据只有三条：
 * 1. 它需要**运动专项知识**（不是所有训练都通用的）；
 * 2. 它有明确的**禁忌与边界**（能说清「别怎么做」）；
 * 3. 它能被几个**关键词**触发（用户会怎么说这件事）。
 * 缺一条就不该建模块，直接写进核心决策规则。
 *
 * ## 两条正文
 *
 * - [core] 一句话纪律，**常驻**核心提示词（模块索引）。没加载正文时也有一条底线。
 * - [body] 详细规则，命中才注入。写「怎么做 / 什么比例 / 什么时候别做」，不要复述核心规则。
 */
